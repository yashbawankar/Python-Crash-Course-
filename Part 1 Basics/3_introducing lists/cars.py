# sorting a list
cars=['bmw','audi','toyota','subaru']
cars.sort()
print(cars)

# reverse sorting
cars.sort(reverse=True)
print(cars)

# sorted()
cars=['bmw','audi','toyota','subaru']
print('Here is the original list:')
print(cars)

print("\nHere id the sorted list:")
print(sorted(cars))

print("\nHere id the original list again:")
print(cars)

# putting alist in reverse order
cars=['bmw','audi','toyota','subaru']
print(cars)
cars.reverse()
print(cars)

# finding a length
cars=['bmw','audi','toyota','subaru']
print(len(cars))

